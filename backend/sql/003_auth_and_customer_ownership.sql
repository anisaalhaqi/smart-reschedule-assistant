BEGIN;

-- 1. Membuat tabel pengguna untuk autentikasi Customer dan Admin.
CREATE TABLE IF NOT EXISTS users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(20) NOT NULL
        CHECK (role IN ('CUSTOMER', 'ADMIN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Menambahkan relasi jadwal dengan akun Customer.
-- Kolom masih nullable agar data jadwal lama tetap aman.
ALTER TABLE schedules
ADD COLUMN IF NOT EXISTS customer_id INTEGER;

-- 3. Menambahkan foreign key ke tabel users.
-- ON DELETE RESTRICT melindungi akun yang masih memiliki jadwal.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'schedules_customer_id_fkey'
          AND conrelid = 'public.schedules'::regclass
    ) THEN
        ALTER TABLE schedules
        ADD CONSTRAINT schedules_customer_id_fkey
        FOREIGN KEY (customer_id)
        REFERENCES users(id)
        ON DELETE RESTRICT;
    END IF;
END
$$;

-- 4. Mempermudah pencarian jadwal berdasarkan pemiliknya.
CREATE INDEX IF NOT EXISTS idx_schedules_customer_id
ON schedules(customer_id);

COMMIT;
BEGIN;
CREATE TABLE IF NOT EXISTS schedules (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 customer_name VARCHAR(120) NOT NULL,
 class_name VARCHAR(120) NOT NULL,
 schedule_date DATE NOT NULL,
 start_time TIME NOT NULL,
 end_time TIME NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED'
   CHECK (status IN ('SCHEDULED','RESCHEDULED','CANCELLED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CHECK (end_time > start_time)
);
CREATE TABLE IF NOT EXISTS available_slots (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 slot_date DATE NOT NULL,
 start_time TIME NOT NULL,
 end_time TIME NOT NULL,
 is_booked BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 CHECK (end_time > start_time),
 UNIQUE (slot_date, start_time)
);
CREATE TABLE IF NOT EXISTS reschedule_requests (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id INTEGER NOT NULL REFERENCES schedules(id) ON DELETE RESTRICT,
 available_slot_id INTEGER NOT NULL REFERENCES available_slots(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
   CHECK (status IN ('PENDING','APPROVED','REJECTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_schedules_date ON schedules(schedule_date);
CREATE INDEX IF NOT EXISTS idx_slots_date_booked ON available_slots(slot_date,is_booked);
CREATE INDEX IF NOT EXISTS idx_requests_status ON reschedule_requests(status);
CREATE INDEX IF NOT EXISTS idx_requests_schedule ON reschedule_requests(schedule_id);
COMMIT;
